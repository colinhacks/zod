export function header(source: string): string {
  return `// generated by packages/datasets from ${source}, do not edit by hand\n\n`;
}

export function scalar(name: string, value: string): string {
  return `export const ${name} = ${JSON.stringify(value)};\n\n`;
}

export function tuple(name: string, values: readonly string[]): string {
  return `export const ${name} = ${JSON.stringify(values)} as const;\n\n`;
}

export function records(name: string, type: string, rows: readonly object[]): string {
  return `export const ${name}: readonly ${type}[] = [\n${rows.map((row) => `  ${JSON.stringify(row)},`).join("\n")}\n];\n\n`;
}

// the previous generated module's code tuple, for the version-bump decision
export function readCodes(source: string, name = "codes"): string[] | undefined {
  const match = source.match(new RegExp(`export const ${name} = (\\[[\\s\\S]*?\\]) as const;`));
  return match ? (JSON.parse(match[1]!.replace(/,\s*\]/, "]")) as string[]) : undefined;
}
